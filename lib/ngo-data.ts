export function getNGOsByState(state: string): NGO[] {
  return NGOS.filter((ngo) => ngo.state === state)
}

export function getNGOsByRegion(state: string, region: string): NGO[] {
  return NGOS.filter((ngo) => ngo.state === state && ngo.region === region)
}

export function getNGOsBySpecialization(specialization: string): NGO[] {
  return NGOS.filter((ngo) => ngo.specialization.includes(specialization))
}

export function searchNGOs(query: string): NGO[] {
  const lowerQuery = query.toLowerCase()
  return NGOS.filter(
    (ngo) =>
      ngo.name.toLowerCase().includes(lowerQuery) ||
      ngo.city.toLowerCase().includes(lowerQuery) ||
      ngo.description.toLowerCase().includes(lowerQuery),
  )
}
